#!/usr/bin/env -S uv run
"""Regenerate Ticket 3.0 Pydantic models from the project JSON Schema."""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PACKAGE_DIR = PROJECT_ROOT / "src/mts_client_integration/models/ticket3"
PACKAGE_SCHEMA = PACKAGE_DIR / "schemas/request.json"
GENERATED = PACKAGE_DIR / "_generated.py"
DEFAULT_SCHEMA_SOURCE = PACKAGE_SCHEMA
SCHEMA_SOURCE_LINE = "# Source: src/mts_client_integration/models/ticket3/schemas/request.json"


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        epilog="See README.md — Regenerating Ticket 3.0 models.",
    )
    parser.add_argument(
        "--schema",
        type=Path,
        default=DEFAULT_SCHEMA_SOURCE,
        help=(
            "Path to merged request JSON Schema "
            "(default: packaged schemas/request.json; use --schema PATH to import a newer schema)"
        ),
    )
    args = parser.parse_args()

    schema_source = args.schema if args.schema.is_absolute() else PROJECT_ROOT / args.schema
    if not schema_source.is_file():
        print(f"Schema not found: {schema_source}", file=sys.stderr)
        print(
            "Provide --schema PATH to a Ticket 3.0 request JSON Schema file. "
            "See README.md — Regenerating Ticket 3.0 models.",
            file=sys.stderr,
        )
        return 1

    schema_source = schema_source.resolve()
    package_schema = PACKAGE_SCHEMA.resolve()
    if schema_source != package_schema:
        PACKAGE_SCHEMA.parent.mkdir(parents=True, exist_ok=True)
        PACKAGE_SCHEMA.write_text(
            schema_source.read_text(encoding="utf-8"),
            encoding="utf-8",
        )
        print(f"Imported schema: {schema_source} -> {PACKAGE_SCHEMA}")
    else:
        print(f"Using packaged schema: {PACKAGE_SCHEMA}")

    cmd = [
        "datamodel-codegen",
        "--input",
        str(PACKAGE_SCHEMA),
        "--input-file-type",
        "jsonschema",
        "--output",
        str(GENERATED),
        "--output-model-type",
        "pydantic_v2.BaseModel",
        "--use-subclass-enum",
        "--field-constraints",
        "--use-standard-collections",
        "--use-union-operator",
        "--target-python-version",
        "3.14",
    ]
    subprocess.run(cmd, check=True)

    text = GENERATED.read_text(encoding="utf-8")
    text = text.replace(
        "# generated by datamodel-codegen:",
        "# Pydantic models generated from Ticket 3.0 request JSON Schema.\n"
        f"{SCHEMA_SOURCE_LINE}\n"
        "# Regenerate: uv run --with datamodel-code-generator \\\n"
        "#   scripts/regenerate_ticket3_models.py\n"
        "# generated by datamodel-codegen:",
        1,
    )
    if "class Model(BaseModel):" in text:
        start = text.index("class Model(BaseModel):")
        end = text.index("class TicketChannelRetail(BaseModel):")
        text = text[:start] + text[end:]
    GENERATED.write_text(text, encoding="utf-8")
    print(f"Regenerated: {GENERATED}")
    print(
        "Review hand-written files if content types or operations changed "
        "— see README.md — Regenerating Ticket 3.0 models.",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
